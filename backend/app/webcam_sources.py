_CAM_ID = re.compile(r"webcams\.opensnow\.com/current/(\d+)\.jpg")


def cam_id(cam_url: str) -> int | None:
    """The OpenSnow cam id in a stored cam URL, or None for any other URL."""
    m = _CAM_ID.search(cam_url)
    return int(m.group(1)) if m else None


def source_for(cam_url: str) -> tuple[str, str] | None:
    """(name, link) of whoever provides this cam, or None if unknown."""
    cid = cam_id(cam_url)
    return SOURCES.get(cid) if cid is not None else None
