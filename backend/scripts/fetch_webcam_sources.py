"""Regenerate app/webcam_sources.py: who owns each OpenSnow cam.

Every cam on opensnow.com/location/<slug>/cams carries the "provided by" name and link
(`provider_name` / `provider_url`) in the page's Nuxt payload. We credit that source rather
than OpenSnow. Run from backend/:  python -m scripts.fetch_webcam_sources
Cams OpenSnow no longer lists (retired cams) get no entry and so show no credit.
"""
import json
import pprint
import re
import time
import urllib.error
import urllib.request
from pathlib import Path

from app.seed import RESORTS, WEBCAMS

OUT = Path(__file__).resolve().parent.parent / "app" / "webcam_sources.py"
CAM_ID = re.compile(r"webcams\.opensnow\.com/current/(\d+)\.jpg")
# OpenSnow slugs we can't derive from the resort's ids.
SLUG_OVERRIDES = {
    "whistler-blackcomb": ["cawhistler"], "mammoth": ["mammothmountain"], "revelstoke": ["carevelstoke"],
    "tremblant": ["catremblant"], "mt-bachelor": ["mountbachelor"], "timberline-lodge": ["timberline"],
}
# OpenSnow's own typos in provider names.
NAME_FIXES = {"Sratton": "Stratton"}


def candidate_slugs(resort: dict) -> list[str]:
    slugs = {resort["id"], resort.get("liftie_id") or "", (resort.get("onthesnow_slug") or "").split("/")[-1]}
    slugs |= {s.replace("-", "") for s in slugs}
    slugs |= set(SLUG_OVERRIDES.get(resort["id"], []))
    return sorted(s for s in slugs if s)


def fetch_cams(slug: str) -> dict[int, tuple[str, str]] | None:
    """{cam id: (provider name, provider url)} for an OpenSnow location, or None if it doesn't exist."""
    req = urllib.request.Request(f"https://opensnow.com/location/{slug}/cams", headers={"User-Agent": "Mozilla/5.0"})
    try:
        html = urllib.request.urlopen(req, timeout=30).read().decode("utf8")
    except urllib.error.HTTPError:
        return None
    data = json.loads(re.search(r'id="__NUXT_DATA__"[^>]*>(.*?)</script>', html, re.S).group(1))
    deref = lambda v: data[v] if isinstance(v, int) else v  # noqa: E731 - Nuxt payloads store values by index
    cams = {}
    for obj in data:
        if isinstance(obj, dict) and "provider_url" in obj and "image_url" in obj:
            name, url = deref(obj["provider_name"]), deref(obj["provider_url"])
            if name and url:
                cams[deref(obj["id"])] = (NAME_FIXES.get(name, name), url)
    return cams


def main() -> None:
    wanted = {int(m.group(1)) for w in WEBCAMS if (m := CAM_ID.search(w["url"]))}
    found: dict[int, tuple[str, str]] = {}
    for resort in RESORTS:
        for slug in candidate_slugs(resort):
            cams = fetch_cams(slug)
            time.sleep(0.4)
            if cams:
                found.update({i: v for i, v in cams.items() if i in wanted})
    missing = sorted(wanted - set(found))
    print(f"{len(found)} of {len(wanted)} cams have a source; {len(missing)} unlisted: {missing}")
    body = pprint.pformat(dict(sorted(found.items())), width=120, sort_dicts=False)
    OUT.write_text(
        '"""Source (provider name, link) of each OpenSnow cam, keyed by OpenSnow cam id.\n\n'
        'GENERATED by scripts/fetch_webcam_sources.py from the "provided by" data on opensnow.com cam pages.\n"""\n'
        "import re\n\n"
        f"SOURCES: dict[int, tuple[str, str]] = {body}\n\n"
        '_CAM_ID = re.compile(r"webcams\\.opensnow\\.com/current/(\\d+)\\.jpg")\n\n\n'
        "def cam_id(cam_url: str) -> int | None:\n"
        '    """The OpenSnow cam id in a stored cam URL, or None for any other URL."""\n'
        "    m = _CAM_ID.search(cam_url)\n"
        "    return int(m.group(1)) if m else None\n\n\n"
        "def source_for(cam_url: str) -> tuple[str, str] | None:\n"
        '    """(name, link) of whoever provides this cam, or None if unknown."""\n'
        "    cid = cam_id(cam_url)\n"
        "    return SOURCES.get(cid) if cid is not None else None\n"
    )


if __name__ == "__main__":
    main()
